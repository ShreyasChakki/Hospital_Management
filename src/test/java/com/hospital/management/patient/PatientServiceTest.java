package com.hospital.management.patient;

import com.hospital.management.dto.PatientDto;
import com.hospital.management.entity.Patient;
import com.hospital.management.exception.BusinessRuleException;
import com.hospital.management.exception.ResourceNotFoundException;
import com.hospital.management.repository.PatientRepository;
import com.hospital.management.service.impl.EntityMapper;
import com.hospital.management.service.impl.PatientServiceImpl;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.Spy;
import org.mockito.junit.jupiter.MockitoExtension;

import java.time.LocalDate;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class PatientServiceTest {

    @Mock
    private PatientRepository patientRepository;

    @Spy
    private EntityMapper mapper = new EntityMapper();

    @InjectMocks
    private PatientServiceImpl patientService;

    private PatientDto validPatientDto;
    private Patient savedPatient;

    @BeforeEach
    void setUp() {
        validPatientDto = new PatientDto();
        validPatientDto.setFullName("Aarav Sharma");
        validPatientDto.setDateOfBirth(LocalDate.of(1995, 5, 10));
        validPatientDto.setGender("Male");
        validPatientDto.setPhoneNumber("9876543210");
        validPatientDto.setEmail("aarav@demo.local");
        validPatientDto.setAddress("104 MG Road, Bengaluru");
        validPatientDto.setBloodGroup("O+");

        savedPatient = new Patient();
        savedPatient.setId(1L);
        savedPatient.setPatientCode("PAT-2026-0001");
        savedPatient.setFullName("Aarav Sharma");
        savedPatient.setDateOfBirth(LocalDate.of(1995, 5, 10));
        savedPatient.setAge(31);
        savedPatient.setGender("Male");
        savedPatient.setPhoneNumber("9876543210");
        savedPatient.setEmail("aarav@demo.local");
        savedPatient.setAddress("104 MG Road, Bengaluru");
        savedPatient.setBloodGroup("O+");
        savedPatient.setRegistrationDate(LocalDate.now());
    }

    @Test
    void registerPatient_shouldSucceedWithAutoGeneratedCode() {
        when(patientRepository.findByPhoneNumber("9876543210")).thenReturn(Optional.empty());
        when(patientRepository.findByEmailIgnoreCase("aarav@demo.local")).thenReturn(Optional.empty());
        when(patientRepository.count()).thenReturn(0L);
        when(patientRepository.findByPatientCode(anyString())).thenReturn(Optional.empty());
        when(patientRepository.save(any(Patient.class))).thenReturn(savedPatient);

        PatientDto result = patientService.registerPatient(validPatientDto);

        assertNotNull(result);
        assertEquals("PAT-2026-0001", result.getPatientCode());
        assertEquals("Aarav Sharma", result.getFullName());
        assertEquals("O+", result.getBloodGroup());
        verify(patientRepository, times(1)).save(any(Patient.class));
    }

    @Test
    void getPatientById_shouldThrowWhenPatientNotFound() {
        when(patientRepository.findById(99L)).thenReturn(Optional.empty());

        ResourceNotFoundException ex = assertThrows(
                ResourceNotFoundException.class,
                () -> patientService.getPatientById(99L)
        );
        assertTrue(ex.getMessage().contains("99"));
    }

    @Test
    void registerPatient_shouldRejectInvalidPhoneAndEmail() {
        validPatientDto.setPhoneNumber("12345");
        assertThrows(BusinessRuleException.class, () -> patientService.registerPatient(validPatientDto));

        validPatientDto.setPhoneNumber("9876543210");
        validPatientDto.setEmail("not-an-email");
        when(patientRepository.findByPhoneNumber("9876543210")).thenReturn(Optional.empty());
        assertThrows(BusinessRuleException.class, () -> patientService.registerPatient(validPatientDto));

        verify(patientRepository, never()).save(any());
    }

    @Test
    void updatePatient_shouldUpdateExistingDetails() {
        PatientDto updateDto = new PatientDto();
        updateDto.setFullName("Aarav S. Sharma");
        updateDto.setAge(32);
        updateDto.setGender("Male");
        updateDto.setPhoneNumber("9876543210");
        updateDto.setEmail("aarav@demo.local");
        updateDto.setAddress("200 Brigade Road, Bengaluru");
        updateDto.setBloodGroup("O+");

        when(patientRepository.findById(1L)).thenReturn(Optional.of(savedPatient));
        when(patientRepository.findByPhoneNumber("9876543210")).thenReturn(Optional.of(savedPatient));
        when(patientRepository.findByEmailIgnoreCase("aarav@demo.local")).thenReturn(Optional.of(savedPatient));
        when(patientRepository.save(any(Patient.class))).thenAnswer(inv -> inv.getArgument(0));

        PatientDto updated = patientService.updatePatient(1L, updateDto);

        assertEquals("Aarav S. Sharma", updated.getFullName());
        assertEquals("200 Brigade Road, Bengaluru", updated.getAddress());
        assertEquals(32, updated.getAge());
    }

    @Test
    void deletePatient_shouldDeleteWhenExists() {
        when(patientRepository.findById(1L)).thenReturn(Optional.of(savedPatient));

        patientService.deletePatient(1L);

        verify(patientRepository, times(1)).delete(savedPatient);
    }
}
